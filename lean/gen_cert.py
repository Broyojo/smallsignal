"""Generate Lean certificates that the solver's symbolic solutions are exact.

usage: python3 lean/gen_cert.py [--numeric] NAME|PATH.cir[@E1:term,E2:term] ...

For each netlist (a name means oracle/corpus/NAME.cir with its sidecar JSON
for the input source), runs `smallsignal analyze --certificate` and writes
lean/Certs/NAME.lean. Assumptions (the sidecar's `assume`, plus any after
`@`, as --ignore, and its Miller splits as --miller) apply: the certificate
is for the assumed element list (a split's C_in and C_out as two params),
and a variant `NAME@M1:ro` is written as NAME_M1_ro. That file states the circuit as an element list in
Smallsignal.Mna's vocabulary, and proves, for symbolic parameters over any
field with the determinant nonzero, that the solver's claimed solution
satisfies KCL at every node and every branch equation, hence `A · x = b` for
the matrix Lean stamps itself (`mna_iff`). It also regenerates
lean/Certs.lean, which imports every certificate.

By default the analysis is symbolic (no operating point), so every
transistor is in its saturated / forward-active small-signal form;
--numeric keeps the operating-point-dependent parameter set instead.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

LEAN = Path(__file__).resolve().parent
REPO = LEAN.parent
CORPUS = REPO / "oracle" / "corpus"
BIN = os.environ.get("SMALLSIGNAL_BIN", str(REPO / "target" / "release" / "smallsignal"))


def opt_node(v) -> str:
    return "none" if v is None else f"(some {v})"


def module_name(name: str) -> str:
    return re.sub(r"\W", "_", name)


def elem(e: dict) -> str:
    k = e["kind"]
    if k == "adm":
        return f".adm {opt_node(e['a'])} {opt_node(e['b'])} ({e['y']})"
    if k == "vccs":
        return f".vccs {opt_node(e['op'])} {opt_node(e['on'])} {opt_node(e['cp'])} {opt_node(e['cn'])} ({e['g']})"
    if k == "cccs":
        return f".cccs {opt_node(e['a'])} {opt_node(e['b'])} {e['ctrl']} ({e['f']})"
    raise ValueError(k)


def branch(b: dict) -> str:
    k = b["kind"]
    if k == "vsrc":
        return f".vsrc {opt_node(b['a'])} {opt_node(b['b'])} ({b['val']})"
    if k == "vcvs":
        return f".vcvs {opt_node(b['a'])} {opt_node(b['b'])} {opt_node(b['cp'])} {opt_node(b['cn'])} ({b['e']})"
    if k == "ccvs":
        return f".ccvs {opt_node(b['a'])} {opt_node(b['b'])} {b['ctrl']} ({b['h']})"
    if k == "ind":
        return f".ind {opt_node(b['a'])} {opt_node(b['b'])} ({b['z']})"
    raise ValueError(k)


def vec(items: list[str]) -> str:
    return "![" + ", ".join(items) + "]"


def certificate_lean(name: str, source: str, input_name: str, cert: dict) -> str:
    nn, nb = len(cert["nodes"]), len(cert["branches"])
    vars_ = ["s"] + [p["var"] for p in cert["params"]]
    sig = " ".join(vars_)
    binder = f"({sig} : K)"
    args = sig
    nums = [f"({n}) / den {args}" for n in cert["num"]]
    node_doc = ", ".join(f"{i} = {'/'.join(ns)}" for i, ns in enumerate(cert["nodes"])) or "none"
    br_doc = ", ".join(f"{i} = {b}" for i, b in enumerate(cert["branches"])) or "none"
    par_doc = "\n".join(
        f"* `{p['var']}` = " + (f"1/{p['name']} (conductance)" if p["conductance"] else p["name"])
        + (" (reactive: appears as `s · …`)" if p["reactive"] else "")
        for p in cert["params"]
    )
    inj = ", ".join(f"({opt_node(t['into'])}, {opt_node(t['outof'])}, ({t['i']}))" for t in cert["inj"])
    simp_kcl = ("Circuit.KCL, circuit, sol, CElem.current, BElem.a, BElem.b, leave, vol, "
                "Fin.sum_univ_succ, Fin.sum_univ_zero")
    return f"""import Smallsignal.Mna

/-!
# Certificate: `{name}` (generated by lean/gen_cert.py; do not edit)

Netlist `{source}`, gain system driven by `{input_name}`.

Node columns: {node_doc}. Branches: {br_doc}.

Variables (MNA values, over any field `K`):
{par_doc}
* `s` = the Laplace variable
-/

set_option linter.unusedVariables false
set_option linter.unnecessarySeqFocus false
set_option maxHeartbeats 0
set_option maxRecDepth 200000

namespace Certs.{module_name(name)}

open Smallsignal Matrix

variable {{K : Type*}} [Field K]

/-- The small-signal circuit, as the solver stamped it. -/
def circuit {binder} : Circuit (Fin {nn}) (Fin {nb}) K where
  elems := [{", ".join(elem(e) for e in cert["elems"])}]
  branch := {vec([branch(b) for b in cert["branch"]])}
  inj := [{inj}]

/-- The solver's determinant. -/
def den {binder} : K := {cert["den"]}

/-- The solver's claimed solution: node voltages, then branch currents. -/
def sol {binder} : Fin {nn} ⊕ Fin {nb} → K :=
  Sum.elim {vec(nums[:nn])} {vec(nums[nn:])}

theorem kcl {binder} (hD : den {args} ≠ 0) :
    ∀ k, (circuit {args}).KCL (sol {args}) k := by
  intro k
  fin_cases k <;> simp [{simp_kcl}] <;> field_simp <;> (try simp only [den]) <;> ring

theorem branchEq {binder} (hD : den {args} ≠ 0) :
    ∀ j, (circuit {args}).BranchEq (sol {args}) j := by
  intro j
  fin_cases j <;> simp [Circuit.BranchEq, circuit, sol, vol] <;> field_simp <;> (try simp only [den]) <;> ring

/-- The solution solves the MNA system Lean stamps from `circuit`. -/
theorem solves {binder} (hD : den {args} ≠ 0) :
    (circuit {args}).A *ᵥ sol {args} = (circuit {args}).rhs :=
  (mna_iff _ _).2 ⟨kcl {args} hD, branchEq {args} hD⟩

end Certs.{module_name(name)}
"""


def main() -> int:
    argv = sys.argv[1:]
    numeric = "--numeric" in argv
    names = [a for a in argv if not a.startswith("--")]
    (LEAN / "Certs").mkdir(exist_ok=True)
    for arg in names:
        base, _, extra = arg.partition("@")
        path = Path(base) if base.endswith(".cir") else CORPUS / f"{base}.cir"
        name = path.stem + ("_" + re.sub(r"\W", "_", extra) if extra else "")
        side = json.loads(path.with_suffix(".json").read_text())
        cmd = [BIN, "analyze", str(path), "--input", side["input"], "--output", side["output"], "--certificate"]
        if not numeric:
            cmd.append("--symbolic")
        ignore = [f"{x['element']}:{x['term']}" for x in (side.get("assume") or {}).get("ignore", [])]
        ignore += [x for x in extra.split(",") if x]
        if ignore:
            cmd += ["--ignore", ",".join(ignore)]
        # Miller splits: the certificate is over the split's C_in and C_out.
        miller = [x["element"] + (f":{x['term']}" if x.get("term") else "")
                  for x in (side.get("assume") or {}).get("miller", [])]
        if miller:
            cmd += ["--miller", ",".join(miller)]
        out = subprocess.run(cmd, capture_output=True, text=True)
        cert = json.loads(out.stdout)
        if "error" in cert:
            print(f"{name}: solver error: {cert['error']}", file=sys.stderr)
            return 1
        rel = os.path.relpath(path, REPO)
        (LEAN / "Certs" / f"{module_name(name)}.lean").write_text(certificate_lean(name, rel, side["input"], cert))
        print(f"{name}: {len(cert['nodes'])} nodes, {len(cert['branches'])} branches, {len(cert['params'])} params")
    mods = sorted(p.stem for p in (LEAN / "Certs").glob("*.lean"))
    (LEAN / "Certs.lean").write_text("".join(f"import Certs.{m}\n" for m in mods))
    return 0


if __name__ == "__main__":
    sys.exit(main())
